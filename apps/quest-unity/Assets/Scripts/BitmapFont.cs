using System.Collections.Generic;
using UnityEngine;

/// <summary>
/// 5×7 点阵字体。为什么自己写：
///   之前用 TextMesh 没有字体材质 → 只有方块没有字；
///   换 UGUI Text 又受 Canvas / RectTransform / 字体资源影响。
///   点阵字直接把像素写进 Texture2D，只要贴图能显示，字就一定能显示。
///
/// 字符集：A-Z 0-9 空格 . - : + / % ( ) °
/// </summary>
public static class BitmapFont
{
    const int GW = 5;   /* 字宽 */
    const int GH = 7;   /* 字高 */

    static readonly Dictionary<char, byte[]> G = new Dictionary<char, byte[]>
    {
        {' ', new byte[]{0x00,0x00,0x00,0x00,0x00}},
        {'A', new byte[]{0x7E,0x11,0x11,0x11,0x7E}},
        {'B', new byte[]{0x7F,0x49,0x49,0x49,0x36}},
        {'C', new byte[]{0x3E,0x41,0x41,0x41,0x22}},
        {'D', new byte[]{0x7F,0x41,0x41,0x22,0x1C}},
        {'E', new byte[]{0x7F,0x49,0x49,0x49,0x41}},
        {'F', new byte[]{0x7F,0x09,0x09,0x09,0x01}},
        {'G', new byte[]{0x3E,0x41,0x49,0x49,0x7A}},
        {'H', new byte[]{0x7F,0x08,0x08,0x08,0x7F}},
        {'I', new byte[]{0x00,0x41,0x7F,0x41,0x00}},
        {'J', new byte[]{0x20,0x40,0x41,0x3F,0x01}},
        {'K', new byte[]{0x7F,0x08,0x14,0x22,0x41}},
        {'L', new byte[]{0x7F,0x40,0x40,0x40,0x40}},
        {'M', new byte[]{0x7F,0x02,0x0C,0x02,0x7F}},
        {'N', new byte[]{0x7F,0x04,0x08,0x10,0x7F}},
        {'O', new byte[]{0x3E,0x41,0x41,0x41,0x3E}},
        {'P', new byte[]{0x7F,0x09,0x09,0x09,0x06}},
        {'Q', new byte[]{0x3E,0x41,0x51,0x21,0x5E}},
        {'R', new byte[]{0x7F,0x09,0x19,0x29,0x46}},
        {'S', new byte[]{0x46,0x49,0x49,0x49,0x31}},
        {'T', new byte[]{0x01,0x01,0x7F,0x01,0x01}},
        {'U', new byte[]{0x3F,0x40,0x40,0x40,0x3F}},
        {'V', new byte[]{0x1F,0x20,0x40,0x20,0x1F}},
        {'W', new byte[]{0x7F,0x20,0x18,0x20,0x7F}},
        {'X', new byte[]{0x63,0x14,0x08,0x14,0x63}},
        {'Y', new byte[]{0x03,0x04,0x78,0x04,0x03}},
        {'Z', new byte[]{0x61,0x51,0x49,0x45,0x43}},
        {'0', new byte[]{0x3E,0x51,0x49,0x45,0x3E}},
        {'1', new byte[]{0x00,0x42,0x7F,0x40,0x00}},
        {'2', new byte[]{0x42,0x61,0x51,0x49,0x46}},
        {'3', new byte[]{0x21,0x41,0x45,0x4B,0x31}},
        {'4', new byte[]{0x18,0x14,0x12,0x7F,0x10}},
        {'5', new byte[]{0x27,0x45,0x45,0x45,0x39}},
        {'6', new byte[]{0x3C,0x4A,0x49,0x49,0x30}},
        {'7', new byte[]{0x01,0x71,0x09,0x05,0x03}},
        {'8', new byte[]{0x36,0x49,0x49,0x49,0x36}},
        {'9', new byte[]{0x06,0x49,0x49,0x29,0x1E}},
        {'.', new byte[]{0x00,0x00,0x40,0x00,0x00}},
        {',', new byte[]{0x00,0x00,0x60,0x00,0x00}},
        {'-', new byte[]{0x08,0x08,0x08,0x08,0x08}},
        {'+', new byte[]{0x08,0x08,0x3E,0x08,0x08}},
        {':', new byte[]{0x00,0x36,0x36,0x00,0x00}},
        {'/', new byte[]{0x20,0x10,0x08,0x04,0x02}},
        {'%', new byte[]{0x23,0x13,0x08,0x64,0x62}},
        {'(', new byte[]{0x00,0x1C,0x22,0x41,0x00}},
        {')', new byte[]{0x00,0x41,0x22,0x1C,0x00}},
        {'o', new byte[]{0x00,0x06,0x09,0x09,0x06}},   /* 当度数符号用 */
        {'_', new byte[]{0x40,0x40,0x40,0x40,0x40}},
    };

    public static int CharWidth(int scale) { return GW * scale; }
    public static int CharHeight(int scale) { return GH * scale; }

    public static int Measure(string s, int scale)
    {
        if (string.IsNullOrEmpty(s)) return 0;
        return s.Length * (GW + 1) * scale;
    }

    /// <summary>把一行字画进像素缓冲（左上角为 (x,y)）</summary>
    public static void Draw(string s, int x, int y, int scale, Color32 col, Color32[] buf, int w, int h)
    {
        if (string.IsNullOrEmpty(s)) return;
        int cx = x;

        foreach (char raw in s)
        {
            char c = char.ToUpperInvariant(raw);
            if (!G.TryGetValue(c, out byte[] g)) g = G['?'.Equals(c) ? ' ' : ' '];

            for (int gx = 0; gx < GW; gx++)
            {
                byte bits = g[gx];
                for (int gy = 0; gy < GH; gy++)
                {
                    if ((bits & (1 << gy)) == 0) continue;

                    for (int sx = 0; sx < scale; sx++)
                    {
                        for (int sy = 0; sy < scale; sy++)
                        {
                            int px = cx + gx * scale + sx;
                            int py = y + gy * scale + sy;
                            if (px < 0 || py < 0 || px >= w || py >= h) continue;
                            buf[py * w + px] = col;
                        }
                    }
                }
            }
            cx += (GW + 1) * scale;
        }
    }
}
